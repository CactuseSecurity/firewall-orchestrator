-- Test of the resolveServiceGroups migration of upgrade/10.0.0.sql (issue #5787). The test task inserts the upgrade file
-- at the run-upgrade markers below, which also shows that the upgrade can be repeated.
-- An isolated schema and temporary tables protect the settings; the transaction is rolled back.
-- This probes: a switched off global modelling setting (in any letter case) becomes the global device specific value,
-- creating the global node if it is missing; the config entries of all users are removed; a repeated upgrade keeps an
-- administrator change; a switched on setting is the default and stores no value.
\set ON_ERROR_STOP 1
BEGIN;
CREATE SCHEMA resolve_service_groups_upgrade_10_0_0_test;
-- the other parts of the upgrade work on the real tables of the public schema
SET LOCAL search_path = resolve_service_groups_upgrade_10_0_0_test, pg_temp, public;
CREATE TEMP TABLE config (config_key varchar, config_value varchar, config_user integer,
    PRIMARY KEY (config_key, config_user));
INSERT INTO config VALUES
    ('modRolloutResolveServiceGroups', 'False', 0),
    ('modRolloutResolveServiceGroups', 'true', 5),
    ('modRolloutBundleTasks', 'false', 0);
CREATE TEMP TABLE device_specific_config_node (id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    node_type varchar, object_key varchar, parent_id bigint, display_name varchar NOT NULL DEFAULT '', sort_order integer,
    UNIQUE (node_type, object_key));
CREATE TEMP TABLE device_specific_config_value (node_id bigint, config_key varchar, config_value jsonb,
    PRIMARY KEY (node_id, config_key));

CREATE FUNCTION pg_temp.assert_migration(expected_value jsonb) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT count(*) FROM device_specific_config_node WHERE node_type = 'global' AND object_key = 'global') <> 1 THEN
        RAISE EXCEPTION 'The global node must exist exactly once';
    END IF;
    IF (SELECT v.config_value FROM device_specific_config_value v JOIN device_specific_config_node n ON n.id = v.node_id
            WHERE n.node_type = 'global' AND v.config_key = 'resolveServiceGroups') IS DISTINCT FROM expected_value THEN
        RAISE EXCEPTION 'The global value of resolveServiceGroups must be %', COALESCE(expected_value::text, 'absent');
    END IF;
    IF (SELECT count(*) FROM device_specific_config_value) <> (CASE WHEN expected_value IS NULL THEN 0 ELSE 1 END) THEN
        RAISE EXCEPTION 'The migration must store no other device specific value';
    END IF;
    IF EXISTS (SELECT 1 FROM config WHERE config_key = 'modRolloutResolveServiceGroups') THEN
        RAISE EXCEPTION 'The config entries of modRolloutResolveServiceGroups must be removed for all users';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM config WHERE config_key = 'modRolloutBundleTasks') THEN
        RAISE EXCEPTION 'Other config entries must stay';
    END IF;
END $$;

-- @run-upgrade-10.0.0
SELECT pg_temp.assert_migration('false'::jsonb);

-- after the upgrade an administrator switches resolving back on; a repeated upgrade must keep it
UPDATE device_specific_config_value SET config_value = 'true'::jsonb WHERE config_key = 'resolveServiceGroups';

-- @run-upgrade-10.0.0
SELECT pg_temp.assert_migration('true'::jsonb);

-- a switched on setting is the default: nothing is stored, the config entry is removed
DELETE FROM device_specific_config_value WHERE config_key = 'resolveServiceGroups';
INSERT INTO config VALUES ('modRolloutResolveServiceGroups', 'true', 0);

-- @run-upgrade-10.0.0
SELECT pg_temp.assert_migration(NULL);
ROLLBACK;
\echo '10.0.0 resolveServiceGroups migration and idempotency checks passed'
